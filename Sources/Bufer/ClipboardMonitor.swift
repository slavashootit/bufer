import AppKit
import CryptoKit

/// Polls the general pasteboard: macOS has no public "pasteboard changed" event,
/// so every clipboard manager compares `changeCount` on a timer.
@MainActor
final class ClipboardMonitor {
    var isPaused = false

    private let pasteboard = NSPasteboard.general
    private let onCapture: (Capture) -> Void
    private var lastChangeCount = -1
    private var timer: Timer?

    /// Markers set by password managers (nspasteboard.org convention).
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private static let excludedApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
    ]

    private static let maxTextBytes = 2_000_000
    private static let maxImageBytes = 40_000_000
    private static let maxRichBytes = 5_000_000

    init(onCapture: @escaping (Capture) -> Void) {
        self.onCapture = onCapture
    }

    func start(interval: TimeInterval = 0.5) {
        timer?.invalidate()
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = interval / 5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call right after writing to the pasteboard ourselves, so our own write is not recorded.
    func skipCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused, let capture = read() else { return }
        onCapture(capture)
    }

    private func read() -> Capture? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretTypes) else { return nil }

        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier,
           Self.excludedApps.contains(id) || Prefs.excludedApps.contains(id) {
            return nil
        }
        let appID = app?.bundleIdentifier
        let appName = app?.localizedName

        // Files first: Finder also puts file names as plain text.
        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Capture(kind: .files, category: .files, files: paths, appID: appID, appName: appName,
                           hash: Self.hash(Data(("f:" + paths.joined(separator: "\n")).utf8)))
        }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= Self.maxTextBytes else { return nil }
            let category = ClipCategory.of(text: text)
            // Keep the original formatting so it can be pasted "as it was".
            var rtf: Data?
            var html: Data?
            if category == .text {
                rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= Self.maxRichBytes ? $0 : nil }
                html = pasteboard.data(forType: .html).flatMap { $0.count <= Self.maxRichBytes ? $0 : nil }
            }
            return Capture(kind: .text, category: category, text: text, rtf: rtf, html: html,
                           appID: appID, appName: appName,
                           hash: Self.hash(Data(("t:" + text).utf8)))
        }

        if let png = pngData(), png.count <= Self.maxImageBytes {
            return Capture(kind: .image, category: .image, imageData: png, appID: appID, appName: appName,
                           hash: Self.hash(png))
        }
        return nil
    }

    private func pngData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        if let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
