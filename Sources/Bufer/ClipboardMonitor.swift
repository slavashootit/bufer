import AppKit
import CryptoKit

/// Polls the general pasteboard: macOS has no public "pasteboard changed" event,
/// so every clipboard manager compares `changeCount` on a timer.
@MainActor
final class ClipboardMonitor {
    var isPaused = false

    private let pasteboard = NSPasteboard.general
    private let onCapture: (Capture) -> Void
    private var lastChangeCount = -1
    private var timer: Timer?

    /// Markers set by password managers (nspasteboard.org convention).
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private static let excludedApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
    ]

    private static let maxTextBytes = 2_000_000
    private static let maxImageBytes = 40_000_000
    private static let maxRichBytes = 5_000_000

    init(onCapture: @escaping (Capture) -> Void) {
        self.onCapture = onCapture
    }

    func start(interval: TimeInterval = 0.5) {
        observeKadr()
        timer?.invalidate()
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = interval / 5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call right after writing to the pasteboard ourselves, so our own write is not recorded.
    func skipCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    /// Kadr marks its screenshots with this type and posts this notification after each write.
    private static let kadrSourceType = "com.slava.kadr.source"
    private static let kadrDidWrite = Notification.Name("com.slava.kadr.clipboardDidWrite")
    private static let kadrBundleID = "com.slava.kadr"

    /// An app that clears the pasteboard and fills it a moment later (encoding a big image in
    /// between) bumps `changeCount` while the board is still empty. Keep looking for this long
    /// before accepting that the change really was "cleared".
    private static let emptyGrace: TimeInterval = 2
    private var emptySince: Date?
    private var emptyCount = -1
    private var observing = false

    private func observeKadr() {
        guard !observing else { return }
        observing = true
        DistributedNotificationCenter.default().addObserver(
            forName: Self.kadrDidWrite, object: nil, queue: .main
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }

        // Still empty: do not mark this change as seen yet, look again shortly.
        if (pasteboard.pasteboardItems ?? []).isEmpty {
            if emptyCount != count {
                emptyCount = count
                emptySince = Date()
            }
            if let since = emptySince, Date().timeIntervalSince(since) < Self.emptyGrace {
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { [weak self] in
                    MainActor.assumeIsolated { self?.check() }
                }
                return
            }
        }
        emptySince = nil
        emptyCount = -1

        guard !isPaused else {
            lastChangeCount = count
            return
        }
        let capture = read()
        // The board changed again while we were reading: what we got may be a mix, read it afresh.
        guard pasteboard.changeCount == count else {
            DispatchQueue.main.async { [weak self] in
                MainActor.assumeIsolated { self?.check() }
            }
            return
        }
        lastChangeCount = count
        if let capture { onCapture(capture) }
    }

    private func read() -> Capture? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretTypes) else { return nil }

        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier,
           Self.excludedApps.contains(id) || Prefs.excludedApps.contains(id) {
            return nil
        }
        var appID = app?.bundleIdentifier
        var appName = app?.localizedName
        // A screenshot belongs to Kadr, not to whatever window happened to be in front.
        // Asked for directly as well: the cached type list can lag behind a write that
        // followed `clearContents()` within the same change count.
        if types.contains(Self.kadrSourceType)
            || pasteboard.data(forType: NSPasteboard.PasteboardType(Self.kadrSourceType)) != nil {
            appID = Self.kadrBundleID
            appName = "Kadr"
        }

        // Files first: Finder also puts file names as plain text.
        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Capture(kind: .files, category: .files, files: paths, appID: appID, appName: appName,
                           hash: Self.hash(Data(("f:" + paths.joined(separator: "\n")).utf8)))
        }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= Self.maxTextBytes else { return nil }
            let category = ClipCategory.of(text: text)
            // Keep the original formatting so it can be pasted "as it was".
            var rtf: Data?
            var html: Data?
            if category == .text {
                rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= Self.maxRichBytes ? $0 : nil }
                html = pasteboard.data(forType: .html).flatMap { $0.count <= Self.maxRichBytes ? $0 : nil }
            }
            return Capture(kind: .text, category: category, text: text, rtf: rtf, html: html,
                           appID: appID, appName: appName,
                           hash: Self.hash(Data(("t:" + text).utf8)))
        }

        if let png = pngData(), png.count <= Self.maxImageBytes {
            return Capture(kind: .image, category: .image, imageData: png, appID: appID, appName: appName,
                           hash: Self.hash(png))
        }
        return nil
    }

    private func pngData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        if let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
